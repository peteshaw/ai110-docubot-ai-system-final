"""
Pass/fail reliability harness for DocuBot and the agentic loop.

The Module 4 tinker shipped a single hit-rate number. That measured retrieval
rank only, which is why three real failures could sit inside a "0.88" score.
This harness asks a stricter question: for each query, did the system do the
right *kind* of thing?

- answerable  -> a non-refusal answer whose top attempt retrieved the right file
- refusal-expected -> an actual refusal (not a confident guess)

Two systems are scored over the same queries:

  oneshot  = the Module 4 behaviour (single retrieve -> answer -> done)
  agentic  = agent.py's bounded verify-and-retry loop

Run without an API key for a deterministic, offline comparison:

    python3 harness.py

Run with Gemini for the full answer path (24 model calls):

    python3 harness.py --llm

Output: a markdown table on stdout and in assets/harness_results.md.
"""

from __future__ import annotations

import argparse
import os
import sys
from dataclasses import dataclass
from pathlib import Path

from agent import REFUSAL, is_refusal, run_agentic
from docubot import DocuBot

# -----------------------------------------------------------
# Query set: the 8 baseline queries plus edge cases the Module 4
# harness never tested.
# -----------------------------------------------------------
CASES = [
    # --- the 8 baseline queries ---
    {"q": "Where is the auth token generated?", "expect": ["AUTH.md"], "kind": "answerable"},
    {"q": "What environment variables are required for authentication?", "expect": ["AUTH.md"], "kind": "answerable"},
    {"q": "How do I connect to the database?", "expect": ["DATABASE.md"], "kind": "answerable"},
    {"q": "Which endpoint lists all users?", "expect": ["API_REFERENCE.md"], "kind": "answerable"},
    {"q": "What does the /api/projects/<project_id> route return?", "expect": ["API_REFERENCE.md"], "kind": "answerable"},
    {"q": "How does a client refresh an access token?", "expect": ["AUTH.md"], "kind": "answerable"},
    {"q": "Which fields are stored in the users table?", "expect": ["DATABASE.md", "API_REFERENCE.md"], "kind": "answerable"},
    {"q": "Is there any mention of payment processing in these docs?", "expect": [], "kind": "refuse"},

    # --- edge cases added for this project ---
    {"q": "How do I authenticate?", "expect": ["AUTH.md"], "kind": "answerable"},          # documented failure 3
    {"q": "What is the capital of France?", "expect": [], "kind": "refuse"},              # off-topic
    {"q": "Tell me about the docs", "expect": [], "kind": "refuse"},                      # documented failure 1
    {"q": "Does the API support GraphQL subscriptions and webhooks?", "expect": [], "kind": "refuse"},  # absent feature

    # --- realistic short queries: one term cannot clear the two-term guardrail ---
    {"q": "authenticate", "expect": ["AUTH.md"], "kind": "answerable"},
    {"q": "login", "expect": ["AUTH.md"], "kind": "answerable"},
    {"q": "database", "expect": ["DATABASE.md"], "kind": "answerable"},
]


@dataclass
class Outcome:
    query: str
    kind: str
    status: str
    passed: bool
    detail: str


def evaluate_case(bot, llm, case, mode: str) -> Outcome:
    """Run one case through one system and decide pass/fail."""
    if mode == "agentic":
        result = run_agentic(bot, llm, case["q"])
        last = result.attempts[-1] if result.attempts else None
        retrieved = last.retrieved if last else []
        refused = is_refusal(result.answer) or result.status == "refused"
        attempts = len(result.attempts)
        detail = f"{attempts} attempt(s)"
    else:
        rows = bot.retrieve_with_scores(case["q"])
        retrieved = [r["filename"] for r in rows]
        refused = not rows
        detail = "1 attempt"
        if not refused:
            snippets = [(r["filename"], r["text"]) for r in rows]
            if llm is None:
                result_answer = "retrieved: " + ", ".join(sorted(set(retrieved)))
            else:
                result_answer = llm.answer_from_snippets(case["q"], snippets)
            refused = is_refusal(result_answer)

    if case["kind"] == "refuse":
        passed = refused
        status = "refused" if refused else "answered (unsafe)"
    else:
        hit = any(name in retrieved for name in case["expect"])
        passed = (not refused) and hit
        status = "answered" if passed else ("refused" if refused else "wrong-source")

    return Outcome(case["q"], case["kind"], status, passed, detail)


def score(bot, llm, mode: str) -> list[Outcome]:
    return [evaluate_case(bot, llm, case, mode) for case in CASES]


def to_markdown(oneshot: list[Outcome], agentic: list[Outcome]) -> str:
    lines = [
        "# Reliability harness — oneshot vs agentic",
        "",
        "Generated by `harness.py`. `pass` means: answerable queries got a grounded,",
        "on-source answer; refusal-expected queries got an actual refusal.",
        "",
        "| # | Query | Expected | Oneshot | Agentic |",
        "|---|---|---|---|---|",
    ]
    for i, (a, b) in enumerate(zip(oneshot, agentic), start=1):
        mark = lambda o: ("✅ pass" if o.passed else f"❌ {o.status}")
        lines.append(f"| {i} | {a.query} | {a.kind} | {mark(a)} | {mark(b)} |")

    lines += ["", "## Summary", ""]
    lines.append(f"- Oneshot: **{sum(o.passed for o in oneshot)}/{len(oneshot)}** passed")
    lines.append(f"- Agentic: **{sum(o.passed for o in agentic)}/{len(agentic)}** passed")

    flips = [b for a, b in zip(oneshot, agentic) if b.passed and not a.passed]
    if flips:
        lines += ["", "## Fixed by the agentic loop", ""]
        lines += [f"- `{o.query}` — now {o.status}" for o in flips]

    regressions = [b for a, b in zip(oneshot, agentic) if a.passed and not b.passed]
    if regressions:
        lines += ["", "## Regressions", ""]
        lines += [f"- `{o.query}` — was passing, now {o.status}" for o in regressions]

    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--llm", action="store_true", help="use Gemini for the answer path")
    parser.add_argument("--out", default="assets/harness_results.md")
    args = parser.parse_args(argv)

    llm = None
    if args.llm:
        from dotenv import load_dotenv
        load_dotenv(os.path.expanduser("~/.config/docubot/env"))
        from llm_client import GeminiClient
        try:
            llm = GeminiClient()
        except RuntimeError as exc:
            print(f"LLM unavailable, falling back to retrieval-only scoring: {exc}", file=sys.stderr)

    bot = DocuBot(docs_folder="docs", llm_client=llm)

    oneshot = score(bot, llm, "oneshot")
    agentic = score(bot, llm, "agentic")
    report = to_markdown(oneshot, agentic)

    print(report)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(f"Written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
